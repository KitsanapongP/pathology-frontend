export function translate(text: string, language: PortalLanguage): string {
  if (language === "th") return text;
  const trimmed = text.trim();
  if (Object.hasOwn(english, trimmed)) return text.replace(trimmed, english[trimmed]);
  const count = trimmed.match(/^พบ (\d+) รายการ$/);
  if (count) return `Found ${count[1]} records`;
  const pagination = trimmed.match(/^(.*?) จาก (\d+) รายการ$/);
  if (pagination) return `${pagination[1]} of ${pagination[2]} records`;
  const upload = trimmed.match(/^เพิ่มเอกสาร (\d+) รายการในหน้านี้แล้ว$/);
  if (upload) return `Added ${upload[1]} documents to this page`;
  const action = trimmed.match(/^(ดู|รายละเอียด|แก้ไข|ลบไฟล์|ตาราง OCR|เลือกรายการ) (.+)$/);
  if (action) return `${({ ดู: "View", รายละเอียด: "Details", แก้ไข: "Edit", ลบไฟล์: "Remove file", "ตาราง OCR": "OCR table", เลือกรายการ: "Select record" } as Record<string, string>)[action[1]]} ${action[2]}`;
  const age = trimmed.match(/^(?:(\d+) ปี · )?(ชาย|หญิง)$/);
  if (age) return `${age[1] ? `${age[1]} years · ` : ""}${age[2] === "ชาย" ? "Male" : "Female"}`;
  const cabinet = trimmed.match(/^ตู้ ([A-Z]\d+)$/);
  if (cabinet) return `Cabinet ${cabinet[1]}`;
  const log = trimmed.match(/^รายละเอียดล็อก #(.+)$/);
  if (log) return `Log details #${log[1]}`;
  return text;
}
